create or replace function pulsechat_private.set_operational_alert(
  target_alert_key text,
  target_severity text,
  target_active boolean,
  target_observed_value numeric,
  target_threshold_value numeric,
  target_detail_code text
)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  insert into public.operational_alerts as alert_row (
    alert_key,
    severity,
    active,
    observed_value,
    threshold_value,
    detail_code,
    first_triggered_at,
    last_evaluated_at,
    resolved_at
  ) values (
    target_alert_key,
    target_severity,
    target_active,
    target_observed_value,
    target_threshold_value,
    target_detail_code,
    case when target_active then timezone('utc'::text, now()) end,
    timezone('utc'::text, now()),
    case when target_active then null else timezone('utc'::text, now()) end
  )
  on conflict (alert_key) do update set
    severity = excluded.severity,
    active = excluded.active,
    observed_value = excluded.observed_value,
    threshold_value = excluded.threshold_value,
    detail_code = excluded.detail_code,
    first_triggered_at = case
      when excluded.active and not alert_row.active then timezone('utc'::text, now())
      when excluded.active then alert_row.first_triggered_at
      else null
    end,
    last_evaluated_at = timezone('utc'::text, now()),
    resolved_at = case
      when excluded.active then null
      when alert_row.active then timezone('utc'::text, now())
      else alert_row.resolved_at
    end;
$$;

revoke all on function pulsechat_private.set_operational_alert(text, text, boolean, numeric, numeric, text)
  from public, anon, authenticated;

create or replace function public.evaluate_operational_alerts()
returns table (
  alert_key text,
  severity text,
  observed_value numeric,
  threshold_value numeric,
  detail_code text
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  metric_value numeric;
  sample_count numeric;
begin
  select count(*)::numeric into metric_value
  from public.client_diagnostics diagnostic
  where diagnostic.event_type = 'crash'
    and diagnostic.occurred_at >= timezone('utc'::text, now()) - interval '15 minutes';
  perform pulsechat_private.set_operational_alert(
    'client_crash_burst', 'critical', metric_value >= 3, metric_value, 3, 'CRASHES_15M'
  );

  select
    count(*)::numeric,
    coalesce(100.0 * count(*) filter (where diagnostic.outcome = 'error') / nullif(count(*), 0), 0)
    into sample_count, metric_value
  from public.client_diagnostics diagnostic
  where diagnostic.event_type = 'api_latency'
    and diagnostic.occurred_at >= timezone('utc'::text, now()) - interval '15 minutes';
  perform pulsechat_private.set_operational_alert(
    'api_error_ratio', 'critical', sample_count >= 20 and metric_value >= 10,
    metric_value, 10, 'API_ERROR_PERCENT_15M'
  );

  select coalesce(percentile_disc(0.95) within group (order by diagnostic.duration_ms), 0)::numeric
    into metric_value
  from public.client_diagnostics diagnostic
  where diagnostic.event_type = 'startup'
    and diagnostic.duration_ms is not null
    and diagnostic.occurred_at >= timezone('utc'::text, now()) - interval '24 hours';
  perform pulsechat_private.set_operational_alert(
    'slow_startup_p95', 'warning', metric_value >= 5000,
    metric_value, 5000, 'STARTUP_P95_MS_24H'
  );

  select
    count(*)::numeric,
    coalesce(100.0 * count(*) filter (where delivery.status = 'error') / nullif(count(*), 0), 0)
    into sample_count, metric_value
  from public.push_delivery_log delivery
  where delivery.created_at >= timezone('utc'::text, now()) - interval '30 minutes'
    and delivery.status in ('ticketed', 'delivered', 'error');
  perform pulsechat_private.set_operational_alert(
    'push_error_ratio', 'critical', sample_count >= 10 and metric_value >= 15,
    metric_value, 15, 'PUSH_ERROR_PERCENT_30M'
  );

  select count(*)::numeric into metric_value
  from public.push_delivery_log delivery
  where delivery.status = 'ticketed'
    and delivery.updated_at < timezone('utc'::text, now()) - interval '30 minutes';
  perform pulsechat_private.set_operational_alert(
    'stale_push_receipts', 'warning', metric_value >= 10,
    metric_value, 10, 'STALE_TICKETS_30M'
  );

  select coalesce(
    extract(epoch from (timezone('utc'::text, now()) - job.last_succeeded_at)) / 60,
    9999
  )::numeric into metric_value
  from (select 1) seed
  left join public.operational_jobs job on job.job_key = 'push_receipt_poll';
  perform pulsechat_private.set_operational_alert(
    'receipt_poller_stale', 'critical', metric_value >= 15,
    metric_value, 15, 'RECEIPT_POLLER_STALE_MINUTES'
  );

  select coalesce(sum(
    case when coalesce(object_row.metadata ->> 'size', '') ~ '^[0-9]+$'
      then (object_row.metadata ->> 'size')::numeric else 0 end
  ), 0) into metric_value
  from storage.objects object_row
  where object_row.bucket_id in ('avatars', 'chat-media');
  perform pulsechat_private.set_operational_alert(
    'storage_budget', 'warning', metric_value >= 536870912,
    metric_value, 536870912, 'STORAGE_BYTES_TOTAL'
  );

  return query
  select alert_row.alert_key, alert_row.severity, alert_row.observed_value,
    alert_row.threshold_value, alert_row.detail_code
  from public.operational_alerts alert_row
  where alert_row.active
  order by case alert_row.severity when 'critical' then 0 else 1 end,
    alert_row.alert_key;
end;
$$;

revoke all on function public.evaluate_operational_alerts() from public, anon, authenticated;
grant execute on function public.evaluate_operational_alerts() to service_role;

-- SQL-editor dashboards remain in the private schema and expose aggregates,
-- not message/profile content.
create or replace view pulsechat_private.rate_limit_dashboard
with (security_invoker = true)
as
select
  state_row.action_key,
  count(*) as actor_count,
  max(state_row.event_count) as max_event_count,
  max(state_row.updated_at) as last_activity_at
from pulsechat_private.rate_limit_state state_row
where state_row.updated_at >= timezone('utc'::text, now()) - interval '24 hours'
group by state_row.action_key;

create or replace view pulsechat_private.storage_dashboard
with (security_invoker = true)
as
select
  object_row.bucket_id,
  count(*) as object_count,
  coalesce(sum(
    case when coalesce(object_row.metadata ->> 'size', '') ~ '^[0-9]+$'
      then (object_row.metadata ->> 'size')::bigint else 0 end
  ), 0) as total_bytes,
  max(object_row.created_at) as newest_object_at
from storage.objects object_row
where object_row.bucket_id in ('avatars', 'chat-media')
group by object_row.bucket_id;

revoke all on pulsechat_private.rate_limit_dashboard from public, anon, authenticated;
revoke all on pulsechat_private.storage_dashboard from public, anon, authenticated;

create or replace function public.run_operational_maintenance()
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  deleted_diagnostics integer := 0;
  deleted_push_logs integer := 0;
  active_alert_count integer := 0;
begin
  delete from public.client_diagnostics diagnostic
  where diagnostic.created_at < timezone('utc'::text, now()) - interval '30 days';
  get diagnostics deleted_diagnostics = row_count;

  delete from public.push_delivery_log delivery
  where delivery.created_at < timezone('utc'::text, now()) - interval '30 days';
  get diagnostics deleted_push_logs = row_count;

  delete from pulsechat_private.rate_limit_state state_row
  where state_row.updated_at < timezone('utc'::text, now()) - interval '2 days';

  delete from public.operational_alerts alert_row
  where not alert_row.active
    and alert_row.resolved_at < timezone('utc'::text, now()) - interval '90 days';

  select count(*) into active_alert_count
  from public.evaluate_operational_alerts();

  insert into public.operational_jobs as job_row (
    job_key, status, last_started_at, last_succeeded_at, processed_count, error_code, updated_at
  ) values (
    'operational_maintenance', 'ok', timezone('utc'::text, now()),
    timezone('utc'::text, now()), deleted_diagnostics + deleted_push_logs, null,
    timezone('utc'::text, now())
  )
  on conflict (job_key) do update set
    status = 'ok',
    last_started_at = excluded.last_started_at,
    last_succeeded_at = excluded.last_succeeded_at,
    processed_count = excluded.processed_count,
    error_code = null,
    updated_at = excluded.updated_at;

  return jsonb_build_object(
    'deletedDiagnostics', deleted_diagnostics,
    'deletedPushLogs', deleted_push_logs,
    'activeAlerts', active_alert_count
  );
end;
$$;

revoke all on function public.run_operational_maintenance() from public, anon, authenticated;
grant execute on function public.run_operational_maintenance() to service_role;

