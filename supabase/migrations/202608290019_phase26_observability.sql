-- PulseChat Phase 26: Prototype V1 production hardening and observability.
-- Run AFTER 202608290018_phase24_rate_limit_ambiguity_fix.sql.
--
-- Privacy boundary:
--   * diagnostics contain categories, timing/status and one-way fingerprints;
--   * message/profile content, request URLs, request bodies, tokens and stacks
--     are never accepted;
--   * operational tables are unavailable to normal app clients;
--   * diagnostics and push ledgers have bounded retention.

-- ---------------------------------------------------------------------------
-- Push tickets are not delivery receipts. Preserve both lifecycle stages and
-- enough bounded polling state for the scheduled receipt worker.
-- ---------------------------------------------------------------------------

alter table public.push_delivery_log
  drop constraint if exists push_delivery_log_status_check;

update public.push_delivery_log
set status = 'ticketed'
where status = 'sent';

alter table public.push_delivery_log
  add column if not exists receipt_attempt_count integer not null default 0,
  add column if not exists last_receipt_check_at timestamptz,
  add column if not exists delivered_at timestamptz;

alter table public.push_delivery_log
  add constraint push_delivery_log_status_check
  check (status in ('claimed', 'ticketed', 'delivered', 'error')),
  add constraint push_delivery_log_receipt_attempt_check
  check (receipt_attempt_count between 0 and 20);

create index if not exists push_delivery_log_receipt_poll_idx
  on public.push_delivery_log (updated_at, id)
  where status = 'ticketed' and ticket_id is not null;

create or replace function public.claim_push_deliveries(
  target_message_id uuid,
  target_deliveries jsonb
)
returns table (
  user_id uuid,
  expo_push_token text
)
language sql
volatile
security definer
set search_path = ''
as $$
  with requested as (
    select distinct
      x.user_id,
      btrim(x.expo_push_token) as expo_push_token
    from jsonb_to_recordset(coalesce(target_deliveries, '[]'::jsonb))
      as x(user_id uuid, expo_push_token text)
    where x.user_id is not null
      and x.expo_push_token is not null
  ),
  allowed as (
    select r.user_id, r.expo_push_token
    from requested r
    join public.push_tokens pt
      on pt.user_id = r.user_id
     and pt.expo_push_token = r.expo_push_token
     and pt.enabled = true
    where exists (
      select 1
      from public.message_receipts mr
      where mr.message_id = target_message_id
        and mr.user_id = r.user_id
        and mr.read_at is null
    )
  ),
  inserted as (
    insert into public.push_delivery_log as delivery_log (
      message_id,
      user_id,
      expo_push_token,
      status
    )
    select target_message_id, a.user_id, a.expo_push_token, 'claimed'
    from allowed a
    on conflict on constraint push_delivery_log_unique_message_token
    do update set
      status = 'claimed',
      ticket_id = null,
      error_code = null,
      error_message = null,
      receipt_attempt_count = 0,
      last_receipt_check_at = null,
      delivered_at = null,
      updated_at = timezone('utc'::text, now())
    where delivery_log.status = 'error'
      and delivery_log.updated_at < timezone('utc'::text, now()) - interval '10 seconds'
    returning delivery_log.user_id, delivery_log.expo_push_token
  )
  select inserted.user_id, inserted.expo_push_token
  from inserted;
$$;

revoke all on function public.claim_push_deliveries(uuid, jsonb)
  from public, anon, authenticated;
grant execute on function public.claim_push_deliveries(uuid, jsonb) to service_role;

-- ---------------------------------------------------------------------------
-- Authenticated, metadata-only client diagnostics.
-- ---------------------------------------------------------------------------

create table if not exists public.client_diagnostics (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  event_type text not null,
  operation text not null,
  platform text not null,
  app_version text not null,
  build_profile text not null,
  duration_ms integer,
  outcome text not null,
  status_code integer,
  error_fingerprint text,
  occurred_at timestamptz not null,
  created_at timestamptz not null default timezone('utc'::text, now()),
  constraint client_diagnostics_event_check
    check (event_type in ('crash', 'startup', 'api_latency')),
  constraint client_diagnostics_operation_check
    check (operation ~ '^[a-z0-9_.-]{1,64}$'),
  constraint client_diagnostics_platform_check
    check (platform in ('android', 'ios', 'web', 'unknown')),
  constraint client_diagnostics_version_check
    check (char_length(app_version) between 1 and 32 and char_length(build_profile) between 1 and 32),
  constraint client_diagnostics_duration_check
    check (duration_ms is null or duration_ms between 0 and 120000),
  constraint client_diagnostics_outcome_check
    check (outcome in ('ok', 'error')),
  constraint client_diagnostics_status_check
    check (status_code is null or status_code between 100 and 599),
  constraint client_diagnostics_fingerprint_check
    check (error_fingerprint is null or error_fingerprint ~ '^[0-9a-f]{8,64}$')
);

create index if not exists client_diagnostics_type_time_idx
  on public.client_diagnostics (event_type, occurred_at desc);
create index if not exists client_diagnostics_operation_time_idx
  on public.client_diagnostics (operation, occurred_at desc);

alter table public.client_diagnostics enable row level security;
revoke all on table public.client_diagnostics from public, anon, authenticated;
grant select, insert, update, delete on table public.client_diagnostics to service_role;
grant usage, select on sequence public.client_diagnostics_id_seq to service_role;

create or replace function public.record_client_diagnostics(target_events jsonb)
returns integer
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  actor_user_id uuid := (select auth.uid());
  requested_count integer;
  inserted_count integer;
begin
  if actor_user_id is null then
    raise exception using errcode = '28000', message = 'Authentication required.';
  end if;
  if jsonb_typeof(target_events) is distinct from 'array' then
    raise exception using errcode = '22023', message = 'Diagnostics must be a JSON array.';
  end if;

  requested_count := jsonb_array_length(target_events);
  if requested_count not between 1 and 20 then
    raise exception using errcode = '22023', message = 'Diagnostics batch must contain 1 to 20 events.';
  end if;

  perform pulsechat_private.enforce_rate_limit(
    actor_user_id,
    'client_diagnostics_hour',
    240,
    3600
  );

  insert into public.client_diagnostics (
    user_id,
    event_type,
    operation,
    platform,
    app_version,
    build_profile,
    duration_ms,
    outcome,
    status_code,
    error_fingerprint,
    occurred_at
  )
  select
    actor_user_id,
    event.event_type,
    event.operation,
    event.platform,
    event.app_version,
    event.build_profile,
    event.duration_ms,
    event.outcome,
    event.status_code,
    event.error_fingerprint,
    event.occurred_at
  from jsonb_to_recordset(target_events) as event(
    event_type text,
    operation text,
    platform text,
    app_version text,
    build_profile text,
    duration_ms integer,
    outcome text,
    status_code integer,
    error_fingerprint text,
    occurred_at timestamptz
  )
  where event.event_type in ('crash', 'startup', 'api_latency')
    and event.operation ~ '^[a-z0-9_.-]{1,64}$'
    and event.platform in ('android', 'ios', 'web', 'unknown')
    and char_length(event.app_version) between 1 and 32
    and char_length(event.build_profile) between 1 and 32
    and (event.duration_ms is null or event.duration_ms between 0 and 120000)
    and event.outcome in ('ok', 'error')
    and (event.status_code is null or event.status_code between 100 and 599)
    and (event.error_fingerprint is null or event.error_fingerprint ~ '^[0-9a-f]{8,64}$')
    and event.occurred_at between timezone('utc'::text, now()) - interval '7 days'
      and timezone('utc'::text, now()) + interval '5 minutes';

  get diagnostics inserted_count = row_count;
  if inserted_count is distinct from requested_count then
    raise exception using errcode = '22023', message = 'One or more diagnostics are invalid.';
  end if;
  return inserted_count;
end;
$$;

revoke all on function public.record_client_diagnostics(jsonb) from public, anon;
grant execute on function public.record_client_diagnostics(jsonb) to authenticated;

